#!/usr/bin/env python3
"""Render quality-matrix-2026-11-01.md from the assembled JSON.

Every number in the .md is emitted from the .json by construction; the
script fails if a quoted cell is missing rather than printing a gap.
CJK languages rank and compare on space-stripped CER: plain WER on
unspaced output reads as ~100 while the text is nearly correct
(the TASK-861 lesson, reproduced by the zh cells in this run).

With --docs-page PATH the script also regenerates the marked winners
block inside the user-facing page (docs/quality-matrix.md), so that
page's numbers are emitted from the same JSON instead of hand-copied.
"""

import argparse
import json
from pathlib import Path

RESULTS = Path(__file__).parent
DATE = "2026-11-01"
DOCS_BLOCK_BEGIN = "<!-- winners table BEGIN: generated by eval/results/matrix_report.py --docs-page; edit the script, not this block -->"
DOCS_BLOCK_END = "<!-- winners table END -->"

data = json.loads((RESULTS / f"quality-matrix-{DATE}.json").read_text())
measured = data["measured"]

model_order = ["parakeet-stock-int8", "whisper-small-attn", "whisper-turbo-attn",
               "whisper-distil-it-attn", "gigaam-v3"]
lang_order = ["fr", "nl", "it", "de", "es", "pt", "ru", "tr", "uk", "pl", "fi",
              "el", "ar", "hi", "vi", "ko", "zh", "fa", "he", "en"]
CJK = {"zh", "ko"}
LANG_NAME = {"fr": "French", "nl": "Dutch", "it": "Italian", "de": "German",
             "es": "Spanish", "pt": "Portuguese", "ru": "Russian", "tr": "Turkish",
             "uk": "Ukrainian", "pl": "Polish", "fi": "Finnish", "el": "Greek",
             "ar": "Arabic", "hi": "Hindi", "vi": "Vietnamese", "ko": "Korean",
             "zh": "Chinese (Mandarin)", "fa": "Persian", "he": "Hebrew", "en": "English"}
DOCS_MODEL_NAME = {"parakeet-stock-int8": "Parakeet TDT",
                   "whisper-small-attn": "Whisper Small",
                   "whisper-turbo-attn": "Whisper Turbo",
                   "whisper-distil-it-attn": "Whisper Distil Italian",
                   "gigaam-v3": "GigaAM v3"}


def metric(cell):
    return cell["cer_stripped"] if "cer_stripped" in cell else cell["wer"]


def cell_text(cell):
    if "cer_stripped" in cell:
        return f"CER {cell['cer_stripped']:.2f} (WER {cell['wer']:.2f})"
    return f"{cell['wer']:.2f}"


def winners():
    """(lang, [models tied at the best metric], value, unit) per language.

    Ties are kept: the it cell has Whisper Turbo and Distil Italian both at
    3.46, and hiding either would misreport the measurement.
    """
    out = []
    for lang in lang_order:
        rows = [(m, metric(c)) for m in model_order
                for c in [measured.get(m, {}).get(lang)] if c is not None]
        if not rows:
            continue
        best = min(v for _, v in rows)
        tied = [m for m, v in rows if v == best]
        any_cell = measured[tied[0]][lang]
        unit = "CER" if "cer_stripped" in any_cell else "WER"
        out.append((lang, tied, best, unit))
    return out


def docs_block():
    """The generated winners table + leaders line for docs/quality-matrix.md."""
    w = winners()
    lines = [DOCS_BLOCK_BEGIN, "| Language | Best model | WER / CER |", "|---|---|---|"]
    for lang, models, value, unit in w:
        val = f"{value:.2f}" if unit == "WER" else f"CER {value:.2f}"
        name = " / ".join(DOCS_MODEL_NAME[m] for m in models)
        lines.append(f"| {LANG_NAME[lang]} | {name} | {val} |")
    leads = []
    for m in model_order:
        langs = [lang for lang, models, _, _ in w if m in models]
        if not langs:
            continue
        ties = {lang for lang, models, _, _ in w if m in models and len(models) > 1}
        outright = [l for l in langs if l not in ties]
        if not outright:
            partners = sorted({x for lang, models, _, _ in w
                               if lang in ties for x in models if x != m})
            names = "/".join(DOCS_MODEL_NAME[x] for x in partners)
            leads.append(f"{DOCS_MODEL_NAME[m]} ties {names} in "
                         f"{'/'.join(LANG_NAME[l] for l in sorted(ties))}")
        elif ties:
            leads.append(f"{DOCS_MODEL_NAME[m]} in {len(outright)} of {len(w)} measured languages "
                         f"outright, tied for best in {'/'.join(LANG_NAME[l] for l in sorted(ties))}")
        elif len(langs) == 1:
            leads.append(f"{DOCS_MODEL_NAME[m]} in {LANG_NAME[langs[0]]}")
        else:
            leads.append(f"{DOCS_MODEL_NAME[m]} in {len(langs)} of {len(w)} measured languages")
    lines.append("")
    lines.append("Leaders: " + "; ".join(leads) + ".")

    def median_rtf(m):
        rtfs = sorted(c["rtf"] for c in measured[m].values())
        n = len(rtfs)
        mid = n // 2
        return (rtfs[mid] if n % 2 else (rtfs[mid - 1] + rtfs[mid]) / 2)
    whispers = [m for m in model_order if m.startswith("whisper-") and measured.get(m)]
    fastest_whisper = min(whispers, key=median_rtf) if whispers else None
    if fastest_whisper and "parakeet-stock-int8" in measured:
        lines.append(f"Speed on this harness (median RTF): {DOCS_MODEL_NAME['parakeet-stock-int8']} {median_rtf('parakeet-stock-int8'):.2f} "
                     f"vs {DOCS_MODEL_NAME[fastest_whisper]} {median_rtf(fastest_whisper):.2f} "
                     f"(the fastest Whisper here); the device-measured gap is wider still.")
    # Italian is the reference bench; the app's model-info WER strings pin
    # against the claim-pins comment below via scripts/check-model-sizes.sh.
    it_vals = {m: measured[m]["it"]["wer"] for m in model_order if "it" in measured.get(m, {})}
    if it_vals:
        lines.append("Italian, every measured model (WER): "
                     + ", ".join(f"{DOCS_MODEL_NAME[m]} {v:.2f}" for m, v in sorted(
                         it_vals.items(), key=lambda kv: DOCS_MODEL_NAME[kv[0]])) + ".")
    pins = {k: it_vals[k] for k in ("whisper-distil-it-attn", "parakeet-stock-int8") if k in it_vals}
    if pins:
        body = " ".join(f"{k}={v:.2f}" for k, v in pins.items())
        lines.append(f"<!-- claim-pins: {body} (scripts/check-model-sizes.sh reads this line; "
                     f"do not reword inside the block) -->")
    lines.append(DOCS_BLOCK_END)
    return "\n".join(lines)


def update_docs_page(path):
    p = Path(path)
    text = p.read_text()
    if DOCS_BLOCK_BEGIN not in text or DOCS_BLOCK_END not in text:
        raise SystemExit(f"{p}: winners-table markers not found; refusing to edit")
    start = text.index(DOCS_BLOCK_BEGIN)
    end = text.index(DOCS_BLOCK_END) + len(DOCS_BLOCK_END)
    p.write_text(text[:start] + docs_block() + text[end:])
    print(f"updated winners block in {p}")


lines = []
lines.append(f"# Per-language quality matrix, measurement pass {data['date']} (TASK-923)")
lines.append("")
lines.append(f"Normalized jiwer WER, clip mode, {data['clips_per_cell']} FLEURS test clips per "
             f"(model, language). Space-stripped CER is quoted and used for ranking on zh. "
             f"Measured {data['date']} on {data['machine']} with sherpa-onnx "
             f"{data['sherpa_version']}, harness eval/fleurs_bench.py at "
             f"{data['harness_commit']} driven in-process unmodified. Numbers are comparable "
             f"within this script only; the normalization differs from run_baseline.py and "
             f"from published FLEURS numbers.")
lines.append("")
lines.append("The whisper rows use the catalog's re-exported *-attn int8 files (re-exported "
             "2026-11-01 for token timestamps; timestamps were left off, they do not affect "
             "text quality). sherpa truncates whisper input at 30 s per clip; this applies "
             "identically to every whisper cell in the run.")
lines.append("")
lines.append("Winners per language:")
lines.append("")
for lang, best_models, value, unit in winners():
    names = ", ".join(best_models)
    lines.append(f"- **{LANG_NAME[lang]} ({lang})**: {names}, {unit} {value:.2f}.")

lines.append("")
lines.append("## Matrix (lower is better; bold = best for the language)")
lines.append("")
lines.append("| Language | " + " | ".join(model_order) + " |")
lines.append("|" + "---|" * (len(model_order) + 1))
for lang in lang_order:
    rows = {m: measured[m][lang] for m in model_order if lang in measured.get(m, {})}
    if not rows:
        continue
    best_m = min(rows, key=lambda m: metric(rows[m]))
    cells = []
    for m in model_order:
        if m not in rows:
            cells.append("n/a")
            continue
        t = cell_text(rows[m])
        cells.append(f"**{t}**" if m == best_m else t)
    lines.append(f"| {LANG_NAME[lang]} ({lang}) | " + " | ".join(cells) + " |")
lines.append("")

lines.append("## Findings")
lines.append("")
di = measured.get("whisper-distil-it-attn", {}).get("it")
dt = measured.get("whisper-turbo-attn", {}).get("it")
if di is None or dt is None:
    di = dt = {"wer": 0, "rtf": 0, "date": "n/a"}  # cell absent; template stays valid
lines.append(f"- **Distil Italian ties Whisper Turbo on the comparable run.** Both "
             f"score {di['wer']:.2f} WER on the 40 Italian clips (distil measured "
             f"{di.get('date')}, addendum cell; turbo {dt.get('date')}), and distil decodes "
             f"faster on this harness (RTF {di['rtf']:.3f} vs {dt['rtf']:.3f}). The 4.3% "
             f"from the older 8-clip desktop benchmark and the 6.8% from the "
             f"device-chain corpus are different clip sets and normalization "
             f"(not comparable); TASK-943 owns the claim sweep.")
tr = measured["parakeet-stock-int8"]["tr"]
lines.append(f"- **parakeet does not actually speak Turkish.** The stock-int8 cell on tr "
             f"scored WER {tr['wer']}; decoded clips come back as phonetic English "
             f"approximations or empty strings (the stored first-hyp sample is empty; a "
             f"diagnostic decode of clip tr_02 returned \"Japon Nuken CC radioactiv C zoom "
             f"ve iodin Till.\" against the reference \"japonya'nın nükleer ajansına göre "
             f"tesiste radyoaktif sezyum ve iyodin...\"), while the same clips score "
             f"{measured['whisper-turbo-attn']['tr']['wer']} on whisper turbo. NVIDIA's "
             f"model card for parakeet-tdt-0.6b-v3 lists 25 languages that include neither "
             f"tr nor no; our models_catalog.json declares both for the sherpa-onnx entry. "
             f"This measurement pass changes no app code: the catalog claim and its surfaces "
             f"are the next phase's problem.")
zh_s = measured["whisper-small-attn"]["zh"]
zh_t = measured["whisper-turbo-attn"]["zh"]
lines.append(f"- **Plain WER is meaningless on zh.** Both whisper cells read ~100 WER "
             f"({zh_s['wer']} / {zh_t['wer']}) while the space-stripped CER is "
             f"{zh_s['cer_stripped']} / {zh_t['cer_stripped']} and the decoded text is "
             f"nearly correct (turbo sample: \"{zh_t['sample']}\"). The table quotes CER "
             f"first for zh and ranks on it.")
hi_t = measured["whisper-turbo-attn"]["hi"]
lines.append(f"- **Hindi is the weakest measured pair.** {hi_t['wer']} WER on turbo, "
             f"{measured['whisper-small-attn']['hi']['wer']} on small; spot-checked ref/hyp "
             f"pairs show real near-miss words, not an instrument artifact. This is the "
             f"model's real behavior on FLEURS hi.")
lines.append("")

lines.append("## Run facts")
lines.append("")
total_wall = sum(c["wall_s"] for m in measured for c in measured[m].values())
lines.append(f"- {sum(len(v) for v in measured.values())} cells measured, "
             f"0 cell errors, total model decode wall time {total_wall/60:.0f} min "
             f"(3 concurrent workers).")
for m in model_order:
    langs = sorted(measured.get(m, {}), key=lang_order.index)
    if not langs:
        continue
    rtf = [measured[m][l]["rtf"] for l in langs]
    wall = sum(measured[m][l]["wall_s"] for l in langs)
    wall_s = f"{wall/60:.1f} min" if wall < 600 else f"{wall/60:.0f} min"
    lines.append(f"- {m}: {len(langs)} language{'s' if len(langs) != 1 else ''}, "
                 f"wall {wall_s}, RTF range {min(rtf):.2f}-{max(rtf):.2f}.")
lines.append("")

lines.append("## NOT MEASURED")
lines.append("")
for nm in data["not_measured"]:
    lines.append(f"- **{nm['model']}** ({', '.join(nm['langs'])}): {nm['reason']}.")
for fc in data.get("failed_cells", []):
    lines.append(f"- **{fc['model']} / {fc['lang']}**: cell failed: {fc['error']}.")
lines.append("")
lines.append("Next phase (surface alignment) owns README/docs/store updates; this file is "
             "measurement only.")

out = RESULTS / f"quality-matrix-{DATE}.md"
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--docs-page", metavar="PATH",
                    help="also regenerate the marked winners block in this page")
args = parser.parse_args()
if args.docs_page:
    update_docs_page(args.docs_page)
